// Builds the "spacify-planner" Ollama model: the base model with the floor-planning guide baked in as its system
// prompt and the settings the planner needs (a context long enough to hold the guide, a steady temperature).
//
//   npm run ai:setup                     # from qwen2.5:3b
//   npm run ai:setup -- qwen2.5:7b       # from another base model (pull it first)
//
// Then set OLLAMA_PLAN_MODEL=spacify-planner in .env.local. The app still sends the guide with every request, so
// the plain base model works too; the baked model just starts ready and keeps the guide with the model.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const base = process.argv[2] || "qwen2.5:3b";
const guide = readFileSync(path.join(root, "lib/server/skills/floor-planning.md"), "utf8");
if (guide.includes('"""')) throw new Error('The guide can\'t contain """ (it ends the Modelfile\'s SYSTEM block).');

const modelfile = `# Generated by scripts/ai-setup.mjs from lib/server/skills/floor-planning.md. Edit the guide, not this file.
FROM ${base}
PARAMETER num_ctx 4096
PARAMETER temperature 0.4
SYSTEM """${guide}"""
`;
mkdirSync(path.join(root, "ollama"), { recursive: true });
const file = path.join(root, "ollama/Modelfile");
writeFileSync(file, modelfile);
console.log(`Wrote ${path.relative(root, file)} (from ${base}).`);
try {
  execFileSync("ollama", ["create", "spacify-planner", "-f", file], { stdio: "inherit" });
  console.log("\nCreated spacify-planner. Add OLLAMA_PLAN_MODEL=spacify-planner to .env.local to use it.");
} catch {
  console.error(`\nCouldn't run "ollama create". Is Ollama installed and running, and is ${base} pulled (ollama pull ${base})?`);
  process.exit(1);
}
